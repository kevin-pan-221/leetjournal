//! User-requested public problem snapshots. Local runs never update solve/review state.
use crate::{
    db::Db,
    error::{AppError, AppResult},
};
use rusqlite::{params, Connection, OptionalExtension};
use serde::{Deserialize, Serialize};
use serde_json::{json, Value};
use std::time::Duration;
use tauri::State;

pub fn initialize(conn: &Connection) -> AppResult<()> {
    conn.execute_batch(
        "CREATE TABLE IF NOT EXISTS offline_problems (
        problem_id TEXT PRIMARY KEY REFERENCES problems(id),
        snapshot TEXT NOT NULL, code TEXT NOT NULL, tests TEXT NOT NULL DEFAULT '',
        saved_at TEXT NOT NULL
    );
    CREATE TABLE IF NOT EXISTS offline_submissions (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        problem_id TEXT NOT NULL REFERENCES problems(id),
        submitted_at TEXT NOT NULL, verdict TEXT NOT NULL,
        passed INTEGER NOT NULL, total INTEGER NOT NULL, runtime_ms REAL NOT NULL,
        code TEXT NOT NULL, detail TEXT NOT NULL DEFAULT ''
    );
    CREATE INDEX IF NOT EXISTS offline_submissions_problem ON offline_submissions(problem_id, id);",
    )?;
    Ok(())
}

#[derive(Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct OfflineProblem {
    pub problem_id: String,
    pub snapshot: Value,
    pub code: String,
    pub tests: String,
    pub saved_at: String,
}

pub(crate) fn read(conn: &Connection, id: &str) -> AppResult<Option<OfflineProblem>> {
    let row = conn
        .query_row(
            "SELECT snapshot,code,tests,saved_at FROM offline_problems WHERE problem_id=?1",
            [id],
            |r| Ok((r.get::<_, String>(0)?, r.get(1)?, r.get(2)?, r.get(3)?)),
        )
        .optional()?;
    row.map(|(snapshot, code, tests, saved_at)| {
        Ok(OfflineProblem {
            problem_id: id.into(),
            snapshot: serde_json::from_str(&snapshot)?,
            code,
            tests,
            saved_at,
        })
    })
    .transpose()
}

#[tauri::command]
pub fn get_offline_problem(problem_id: String, db: State<Db>) -> AppResult<Option<OfflineProblem>> {
    read(&db.0.lock().unwrap(), &problem_id)
}

#[tauri::command]
pub fn list_offline_problems(db: State<Db>) -> AppResult<Vec<String>> {
    let conn = db.0.lock().unwrap();
    let mut stmt = conn.prepare("SELECT problem_id FROM offline_problems ORDER BY problem_id")?;
    let ids = stmt
        .query_map([], |r| r.get(0))?
        .collect::<Result<Vec<_>, _>>()?;
    Ok(ids)
}

fn slug_from_url(value: &str) -> AppResult<String> {
    let url =
        reqwest::Url::parse(value).map_err(|_| AppError::Message("Invalid problem URL".into()))?;
    if url.scheme() != "https"
        || !matches!(url.host_str(), Some("leetcode.com" | "www.leetcode.com"))
    {
        return Err(AppError::Message(
            "Only public LeetCode problems can be saved".into(),
        ));
    }
    let mut segments = url.path_segments().into_iter().flatten();
    let prefix = segments.next();
    let slug = segments.next().unwrap_or("");
    if prefix != Some("problems")
        || slug.is_empty()
        || !slug
            .bytes()
            .all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'-')
    {
        return Err(AppError::Message("Invalid problem slug".into()));
    }
    Ok(slug.into())
}

/// Original statements for NeetCode problems whose LeetCode statement is Premium-only.
/// Generated by scripts/judge/build.py; stored without contacting LeetCode.
fn bundled_snapshot(slug: &str) -> Option<Value> {
    static BUNDLED: std::sync::OnceLock<Value> = std::sync::OnceLock::new();
    BUNDLED
        .get_or_init(|| {
            serde_json::from_str(include_str!("offline_bundled.json")).unwrap_or(Value::Null)
        })
        .get(slug)
        .cloned()
}

fn store(conn: &Connection, id: &str, snapshot: &Value) -> AppResult<OfflineProblem> {
    let starter = snapshot["codeSnippets"]
        .as_array()
        .and_then(|items| items.iter().find(|v| v["langSlug"] == "python3"))
        .and_then(|v| v["code"].as_str())
        .unwrap_or("# No Python starter available.\n");
    conn.execute("INSERT INTO offline_problems(problem_id,snapshot,code,saved_at) VALUES(?1,?2,?3,?4)
        ON CONFLICT(problem_id) DO UPDATE SET snapshot=excluded.snapshot,saved_at=excluded.saved_at",
        params![id, serde_json::to_string(snapshot)?, starter, chrono::Utc::now().to_rfc3339()])?;
    read(conn, id)?.ok_or_else(|| AppError::Message("Could not save offline problem".into()))
}

#[tauri::command]
pub async fn download_offline_problem(
    problem_id: String,
    db: State<'_, Db>,
) -> AppResult<OfflineProblem> {
    download_to_db(&problem_id, &db, &download_client()?)
        .await
        .map_err(|failure| failure.error)
}

pub(crate) struct DownloadFailure {
    pub error: AppError,
    // Only a missing public statement is safe to skip in a batch. Transport,
    // authentication, rate-limit and storage failures stop further requests.
    pub unavailable: bool,
}

impl From<AppError> for DownloadFailure {
    fn from(error: AppError) -> Self {
        Self {
            error,
            unavailable: false,
        }
    }
}

pub(crate) fn download_client() -> AppResult<reqwest::Client> {
    reqwest::Client::builder()
        .timeout(Duration::from_secs(25))
        .redirect(reqwest::redirect::Policy::none())
        .build()
        .map_err(|e| AppError::Message(e.to_string()))
}

pub(crate) async fn download_to_db(
    problem_id: &str,
    db: &Db,
    client: &reqwest::Client,
) -> Result<OfflineProblem, DownloadFailure> {
    let url: String =
        db.0.lock()
            .unwrap()
            .query_row(
                "SELECT leetcode_url FROM problems WHERE id=?1",
                [&problem_id],
                |r| r.get(0),
            )
            .map_err(AppError::from)?;
    let slug = slug_from_url(&url)?;
    if let Some(snapshot) = bundled_snapshot(&slug) {
        return store(&db.0.lock().unwrap(), problem_id, &snapshot).map_err(Into::into);
    }
    let mut response = client.post("https://leetcode.com/graphql/").json(&json!({
        "query": "query OfflineProblem($titleSlug: String!) { question(titleSlug: $titleSlug) { title content exampleTestcases metaData codeSnippets { langSlug code } } }",
        "variables": {"titleSlug": slug}
    })).send().await.map_err(|_| AppError::Message("Could not reach LeetCode. Connect to the internet to save this problem.".into()))?
        .error_for_status().map_err(|e| AppError::Message(match e.status().map(|s| s.as_u16()) {
            Some(429) => "LeetCode is rate-limiting downloads. Wait before resuming; saved copies are safe.",
            Some(401 | 403) => "LeetCode blocked this download. Try again later; restricted access is not bypassed.",
            _ => "LeetCode could not provide this download. Try again later.",
        }.into()))?;
    let mut bytes = Vec::new();
    while let Some(chunk) = response
        .chunk()
        .await
        .map_err(|e| AppError::Message(e.to_string()))?
    {
        if bytes.len() + chunk.len() > 2_000_000 {
            return Err(AppError::Message("Problem is too large to save".into()).into());
        }
        bytes.extend_from_slice(&chunk);
    }
    let data: Value = serde_json::from_slice(&bytes).map_err(AppError::from)?;
    if data
        .get("errors")
        .and_then(Value::as_array)
        .is_some_and(|e| !e.is_empty())
    {
        return Err(AppError::Message(
            "LeetCode returned an error. Wait before trying again.".into(),
        )
        .into());
    }
    let mut question = data["data"]["question"].clone();
    if question["content"]
        .as_str()
        .is_none_or(|s| s.trim().is_empty())
    {
        return Err(DownloadFailure {
            error: AppError::Message(
                "This problem's public statement is unavailable. No offline copy was saved.".into(),
            ),
            unavailable: true,
        });
    }
    let previous = read(&db.0.lock().unwrap(), problem_id)?;
    crate::offline_images::cache(
        client,
        &mut question,
        previous.as_ref().map(|p| &p.snapshot),
    )
    .await;
    store(&db.0.lock().unwrap(), problem_id, &question).map_err(Into::into)
}

#[tauri::command]
pub fn save_offline_draft(
    problem_id: String,
    code: String,
    tests: String,
    db: State<Db>,
) -> AppResult<()> {
    if code.len() > 200_000 || tests.len() > 200_000 {
        return Err(AppError::Message(
            "Keep code and tests below 200 KB each".into(),
        ));
    }
    if db.0.lock().unwrap().execute(
        "UPDATE offline_problems SET code=?2,tests=?3 WHERE problem_id=?1",
        params![problem_id, code, tests],
    )? == 0
    {
        return Err(AppError::Message(
            "Save this problem for offline use first".into(),
        ));
    }
    Ok(())
}

#[derive(Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct OfflineSubmission {
    #[serde(default)]
    pub id: i64,
    #[serde(default)]
    pub problem_id: String,
    #[serde(default)]
    pub submitted_at: String,
    pub verdict: String,
    pub passed: i64,
    pub total: i64,
    pub runtime_ms: f64,
    pub code: String,
    #[serde(default)]
    pub detail: String,
}

const SUBMISSION_HISTORY: i64 = 50;

/// Local judge results are a practice log only; they never change solve or review state.
#[tauri::command]
pub fn record_offline_submission(
    problem_id: String,
    submission: OfflineSubmission,
    db: State<Db>,
) -> AppResult<OfflineSubmission> {
    record_submission(&db.0.lock().unwrap(), &problem_id, submission)
}

pub(crate) fn record_submission(
    conn: &Connection,
    problem_id: &str,
    mut submission: OfflineSubmission,
) -> AppResult<OfflineSubmission> {
    const VERDICTS: [&str; 5] = [
        "accepted",
        "wrong-answer",
        "runtime-error",
        "time-limit",
        "compile-error",
    ];
    if !VERDICTS.contains(&submission.verdict.as_str())
        || submission.code.len() > 200_000
        || submission.detail.len() > 64_000
        || !(0..=100_000).contains(&submission.total)
        || !(0..=submission.total).contains(&submission.passed)
        || !submission.runtime_ms.is_finite()
        || submission.runtime_ms < 0.0
    {
        return Err(AppError::Message("Invalid submission result".into()));
    }
    submission.problem_id = problem_id.into();
    submission.submitted_at = chrono::Utc::now().to_rfc3339();
    conn.execute(
        "INSERT INTO offline_submissions(problem_id,submitted_at,verdict,passed,total,runtime_ms,code,detail)
         VALUES(?1,?2,?3,?4,?5,?6,?7,?8)",
        params![
            problem_id,
            submission.submitted_at,
            submission.verdict,
            submission.passed,
            submission.total,
            submission.runtime_ms,
            submission.code,
            submission.detail
        ],
    )?;
    submission.id = conn.last_insert_rowid();
    conn.execute(
        "DELETE FROM offline_submissions WHERE problem_id=?1 AND id NOT IN
         (SELECT id FROM offline_submissions WHERE problem_id=?1 ORDER BY id DESC LIMIT ?2)",
        params![problem_id, SUBMISSION_HISTORY],
    )?;
    Ok(submission)
}

#[tauri::command]
pub fn list_offline_submissions(
    problem_id: String,
    db: State<Db>,
) -> AppResult<Vec<OfflineSubmission>> {
    list_submissions(&db.0.lock().unwrap(), &problem_id)
}

pub(crate) fn list_submissions(
    conn: &Connection,
    problem_id: &str,
) -> AppResult<Vec<OfflineSubmission>> {
    let mut stmt = conn.prepare(
        "SELECT id,submitted_at,verdict,passed,total,runtime_ms,code,detail FROM offline_submissions
         WHERE problem_id=?1 ORDER BY id DESC",
    )?;
    let rows = stmt
        .query_map([problem_id], |r| {
            Ok(OfflineSubmission {
                id: r.get(0)?,
                problem_id: problem_id.into(),
                submitted_at: r.get(1)?,
                verdict: r.get(2)?,
                passed: r.get(3)?,
                total: r.get(4)?,
                runtime_ms: r.get(5)?,
                code: r.get(6)?,
                detail: r.get(7)?,
            })
        })?
        .collect::<Result<Vec<_>, _>>()?;
    Ok(rows)
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn validates_problem_source() {
        assert_eq!(
            slug_from_url("https://leetcode.com/problems/two-sum/description/").unwrap(),
            "two-sum"
        );
        for url in [
            "http://leetcode.com/problems/x",
            "https://evil.test/problems/x",
            "https://leetcode.com/other/x",
            "https://leetcode.com/problems/../",
        ] {
            assert!(slug_from_url(url).is_err());
        }
    }
    #[test]
    fn refresh_preserves_work_and_cache_round_trips() {
        let conn = Connection::open_in_memory().unwrap();
        conn.execute_batch(
            "CREATE TABLE problems(id TEXT PRIMARY KEY); INSERT INTO problems VALUES('one')",
        )
        .unwrap();
        initialize(&conn).unwrap();
        initialize(&conn).unwrap();
        assert!(read(&conn, "one").unwrap().is_none());
        let snapshot = json!({"content":"statement", "codeSnippets":[{"langSlug":"python3", "code":"starter"}]});
        assert_eq!(store(&conn, "one", &snapshot).unwrap().code, "starter");
        conn.execute(
            "UPDATE offline_problems SET code='my solution',tests='my tests'",
            [],
        )
        .unwrap();
        let refreshed = store(&conn, "one", &json!({"content":"new statement"})).unwrap();
        assert_eq!(refreshed.code, "my solution");
        assert_eq!(refreshed.tests, "my tests");
        assert_eq!(refreshed.snapshot["content"], "new statement");
    }

    #[test]
    fn bundled_premium_statements_are_available_offline() {
        for slug in ["alien-dictionary", "meeting-rooms", "walls-and-gates"] {
            let snapshot = bundled_snapshot(slug).expect(slug);
            assert!(snapshot["content"].as_str().is_some_and(|c| !c.is_empty()));
            assert!(snapshot["codeSnippets"][0]["code"].as_str().is_some());
        }
        assert!(bundled_snapshot("two-sum").is_none());
    }

    #[test]
    fn submissions_are_validated_and_capped() {
        let conn = Connection::open_in_memory().unwrap();
        conn.execute_batch(
            "CREATE TABLE problems(id TEXT PRIMARY KEY); INSERT INTO problems VALUES('one')",
        )
        .unwrap();
        initialize(&conn).unwrap();
        let make = |verdict: &str, passed| OfflineSubmission {
            id: 0,
            problem_id: String::new(),
            submitted_at: String::new(),
            verdict: verdict.into(),
            passed,
            total: 10,
            runtime_ms: 1.5,
            code: "class Solution: pass".into(),
            detail: String::new(),
        };
        assert!(record_submission(&conn, "one", make("hacked", 1)).is_err());
        assert!(record_submission(&conn, "one", make("accepted", 11)).is_err());
        for _ in 0..(SUBMISSION_HISTORY + 5) {
            record_submission(&conn, "one", make("wrong-answer", 3)).unwrap();
        }
        let last = record_submission(&conn, "one", make("accepted", 10)).unwrap();
        let rows = list_submissions(&conn, "one").unwrap();
        assert_eq!(rows.len() as i64, SUBMISSION_HISTORY);
        assert_eq!(rows[0].id, last.id);
        assert_eq!(rows[0].verdict, "accepted");
    }
}
